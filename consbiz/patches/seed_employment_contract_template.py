def execute():
	if not frappe.db.table_exists("Employment Contract Template"):
		frappe.reload_doc("consbiz", "doctype", "employment_contract_template")
	if frappe.db.count("Employment Contract Template"):
		return
	doc = frappe.get_doc(
		{
			"doctype": "Employment Contract Template",
			"title": TITLE,
			"is_default": 1,
			"heading": "สัญญาจ้างพนักงาน",
			"terms": TERMS,
		}
	)
	doc.insert(ignore_permissions=True)
	# Frappe เติมบริษัทจากค่าตั้งต้นของผู้ใช้ให้ช่อง Link Company: แม่แบบเริ่มต้นต้องใช้ได้ทุกบริษัท
	doc.db_set("company", None)
